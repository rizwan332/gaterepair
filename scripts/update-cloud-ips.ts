/**
 * Regenerates lib/cloud-ips.ts from the cloud providers' own published lists.
 *
 *   npm run update:cloud-ips
 *
 * The dashboard names the network ("AWS server") for a direct visit from one
 * of these ranges. Re-run every month or two, the lists change.
 * shortcut: AWS EC2, Google Cloud and DigitalOcean only, IPv4 only. Add Azure
 * (its list sits behind a download page) if bots from it show up in the log.
 */

import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

const toNum = (ip: string) => ip.split('.').reduce((n, o) => n * 256 + Number(o), 0)
function cidr(prefix: string): [number, number] {
  const [ip, bits] = prefix.split('/')
  const start = toNum(ip)
  return [start, start + 2 ** (32 - Number(bits)) - 1]
}

async function main() {
  const aws = await (await fetch('https://ip-ranges.amazonaws.com/ip-ranges.json')).json()
  const gcp = await (await fetch('https://www.gstatic.com/ipranges/cloud.json')).json()
  const dig = await (await fetch('https://www.digitalocean.com/geo/google.csv')).text()

  const sources: [string, string[]][] = [
    ['AWS', aws.prefixes.filter((p: any) => p.service === 'EC2').map((p: any) => p.ip_prefix)],
    ['Google Cloud', gcp.prefixes.map((p: any) => p.ipv4Prefix).filter(Boolean)],
    ['DigitalOcean', dig.split('\n').map((l) => l.split(',')[0]).filter((p) => /^\d+\.\d+\.\d+\.\d+\/\d+$/.test(p))],
  ]

  const ranges: [number, number, number][] = []
  sources.forEach(([, prefixes], provider) => {
    const sorted = prefixes.map(cidr).sort((a, b) => a[0] - b[0])
    for (const [s, e] of sorted) {
      const last = ranges[ranges.length - 1]
      if (last && last[2] === provider && s <= last[1] + 1) last[1] = Math.max(last[1], e)
      else ranges.push([s, e, provider])
    }
  })
  ranges.sort((a, b) => a[0] - b[0])
  if (ranges.length < 500) throw new Error(`only ${ranges.length} ranges: a provider list probably failed to download`)

  const out = `// Generated by scripts/update-cloud-ips.ts on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// [first IP, last IP, provider index] as unsigned 32-bit numbers, sorted by first IP.
export const CLOUD_PROVIDERS = ${JSON.stringify(sources.map(([name]) => name))}
export const CLOUD_RANGES: [number, number, number][] = ${JSON.stringify(ranges)}
`
  writeFileSync(join(__dirname, '..', 'lib', 'cloud-ips.ts'), out)
  console.log(`lib/cloud-ips.ts: ${ranges.length} ranges`)

  // Self-check against the generated file. 3.94.106.105 is the EC2 bot from the 2 Nov 2026 log.
  const { cloudProvider } = await import('../lib/visitor-context')
  const expect = { '3.94.106.105': 'AWS', '34.0.0.1': 'Google Cloud', '104.131.0.1': 'DigitalOcean', '1.1.1.1': undefined, '172.58.0.1': undefined, '2600::1': undefined }
  for (const [ip, want] of Object.entries(expect)) {
    if (cloudProvider(ip) !== want) throw new Error(`cloudProvider(${ip}) = ${cloudProvider(ip)}, expected ${want}`)
  }
  console.log('self-check passed')
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
