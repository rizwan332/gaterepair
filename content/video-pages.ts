// Fail the build rather than publish a watch page with no provenance for its
// date. Runs wherever this module is imported: the watch pages, the hub and the
// sitemap.
const missing = videos.filter((v) => !VIDEO_PAGES[v.slug]).map((v) => v.slug)
if (missing.length > 0) {
  throw new Error(
    `content/video-pages.ts has no entry for ${missing.join(', ')}. ` +
      'Add an uploadDate for each (the date it was first published, with its source) before building.',
  )
}

export const videoBySlug = (slug: string) => videos.find((v) => v.slug === slug)

export function videoPageMeta(slug: string): VideoPageMeta {
  const meta = VIDEO_PAGES[slug]
  if (!meta) throw new Error(`No watch-page entry for video "${slug}".`)
  return meta
}

export const watchTitle = (video: SiteVideo) => VIDEO_PAGES[video.slug]?.shortTitle ?? video.title

/**
 * The page a video's category belongs to. Categories are service or brand
 * slugs by construction (scripts/process-videos.ts), so this resolves them
 * rather than keeping a second hand-written map that could drift.
 */
export function categoryLink(category: string): { label: string; href: string } | null {
  const service = serviceBySlug(category)
  if (service) return { label: service.name, href: `/services/${service.slug}` }
  const brand = brandBySlug(category)
  if (brand) return { label: `${brand.name} gate operators`, href: `/brands/${brand.slug}` }
  if (category === 'testimonial') return { label: 'Customer testimonials', href: '/testimonials' }
  return null
}

/** Same category first, then everything else, so a viewer stays on topic. */
export function relatedVideos(video: SiteVideo, limit = 6): SiteVideo[] {
  const same = videos.filter((v) => v.category === video.category && v.slug !== video.slug)
  const rest = videos.filter((v) => v.category !== video.category)
  return [...same, ...rest].slice(0, limit)
}

export type VideoGroup = { key: string; label: string; href: string; videos: SiteVideo[] }

/**
 * Videos grouped for the hub: services in their site order, then brands by
 * priority, then testimonials. A category that resolves to nothing is still
 * listed under "More repairs" rather than silently dropped from the hub —
 * a watch page nothing links to is an orphan.
 */
export function videoGroups(): VideoGroup[] {
  const order = [
    ...services.map((s) => s.slug),
    ...[...brands].sort((a, b) => a.priority - b.priority).map((b) => b.slug),
    'testimonial',
  ]
  const groups: VideoGroup[] = []
  for (const key of order) {
    const link = categoryLink(key)
    const inGroup = videos.filter((v) => v.category === key)
    if (link && inGroup.length > 0) groups.push({ key, ...link, videos: inGroup })
  }
  const grouped = new Set(groups.flatMap((g) => g.videos.map((v) => v.slug)))
  const orphans = videos.filter((v) => !grouped.has(v.slug))
  if (orphans.length > 0) {
    groups.push({ key: 'other', label: 'More repairs', href: VIDEO_HUB_PATH, videos: orphans })
  }
  return groups
}
