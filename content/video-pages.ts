/**
 * Per-video watch-page data.
 *
 * ── WHY WATCH PAGES EXIST ───────────────────────────────────────────────────
 * Search Console was reporting the site's videos as not indexed, and two causes
 * were verified against the live site on 13 Sep 2026:
 *
 *  1. No video element in the HTML. `LazyVideo` renders a poster and a button
 *     and only creates the <video> after a click. Googlebot does not click, so
 *     on every page it found a VideoObject describing a video that was not
 *     there. The only <iframe> on those pages was Tag Manager's noscript tag.
 *
 *  2. No watch pages. Google indexes a video only when it is the main content
 *     of its page. All 33 pages carrying VideoObject were text pages of 517 to
 *     2,545 words with video as a supporting section — and 21 of the 30 clips
 *     they described were claimed by two or three pages at once, so Google had
 *     no single page to index any of them under.
 *
 * So each video now has exactly one page at /repair-videos/<slug> where it is
 * the main content, server-rendered as a real <video>, and VideoObject lives
 * only there. Every other page keeps its tile and links to the watch page.
 *
 * ── WHY THIS IS A SEPARATE FILE ─────────────────────────────────────────────
 * content/video-manifest.ts is generated by scripts/process-videos.ts and only
 * `title` and `description` survive a regeneration. Anything else hand-written
 * lives here, keyed by the same slug.
 *
 * ── UPLOAD DATES ────────────────────────────────────────────────────────────
 * `uploadDate` is when the video was first published, which is what schema.org
 * and Google mean by it. Every clip previously carried '2026-08-01' — the day
 * the site was migrated, hardcoded in four files — so every one of them claimed
 * the same publication date regardless of when it went online. The dates below
 * come from two independent sources that agree with each other:
 *
 *  - WordPress footage (25 clips): uploaded to the old WordPress site on this
 *    same domain. The upload dump files them under wordpress-uploads/2026/05/,
 *    and the file timestamps inside it read 14 May 2026 (the testimonial, 15).
 *
 *  - Client footage (8 clips): first published on this site, dated by the git
 *    commit that first added each file to public/videos/. The phone masters in
 *    client-assets/videos/ carry a creation_time of 5 Aug 2026, one day
 *    earlier, which is when they were exported rather than when they went live.
 *
 * A new video without an entry here fails the build — see the guard below —
 * rather than shipping with an invented date.
 *
 * `shortTitle` is used for the <title> tag where the full title, which stays as
 * the H1, would run past Google's ~60-character display budget.
 */

